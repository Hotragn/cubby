// Inspector log exports. The weekly file is the daily format repeated per day.
import { presence } from "../public/lib/rules.js";
import { fmt, dur } from "../public/lib/time.js";

export function logRows(d) {
  const name = (e) => e.staff ? d.staff.find((s) => s.id === e.staff)?.name : (e.kids ?? []).map((k) => d.roster.find((c) => c.id === k)?.name).join(", ");
  return [...d.events].sort((a, b) => (a.start ?? 0) - (b.start ?? 0)).map((e) => ({
    time: e.type === "nap" ? `${fmt(e.start)}–${e.end != null ? fmt(e.end) : "?"}` : fmt(e.start), who: name(e), type: e.type,
    what: { arrive: `Signed in${e.by ? `, by ${e.by}` : ""}`, depart: `Signed out${e.by ? `, to ${e.by}` : ""}`, staff_in: "Staff in", staff_out: "Staff out", meal: `${e.meal ?? "Meal"}: ${e.food ?? ""} (${e.amount ?? "amount not noted"})`, bottle: `Bottle ${e.oz ?? "?"} oz`, nap: `Nap${e.end != null ? ` ${dur(e.end - e.start)}` : ""}`, sleep_check: `Sleep check${e.position ? `, ${e.position}` : ""}${e.by ? `, by ${e.by}` : ""}`, diaper: e.toilet ? `Potty (${e.kind ?? ""})` : `Diaper: ${e.kind ?? ""}`, incident: `Incident: ${e.what ?? ""}${e.action ? `; ${e.action}` : ""}`, med: `Medication: ${e.med ?? "?"} ${e.dose ?? "?"}, by ${e.by ?? "?"}`, mood: `Mood: ${e.mood}`, activity: e.what, note: e.what }[e.type],
    quote: e.quote,
  }));
}

function download(blob, name) {
  const a = document.createElement("a"); a.href = URL.createObjectURL(blob); a.download = name;
  document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(a.href), 5000);
}

export function exportCsv(days, base) {
  const esc = (s) => `"${String(s ?? "").replace(/"/g, '""')}"`;
  const lines = ["date,time,child,type,entry,source_note"];
  for (const d of days) for (const r of logRows(d)) lines.push([d.date, r.time, r.who, r.type, r.what, r.quote].map(esc).join(","));
  download(new Blob([lines.join("\n")], { type: "text/csv" }), `${base}.csv`);
}

export async function exportPdf(days, pack, base, title) {
  const pdfMod = await import("jspdf");
  const jsPDF = pdfMod.jsPDF ?? pdfMod.default;
  const atMod = await import("jspdf-autotable");
  const autoTable = typeof atMod.autoTable === "function" ? atMod.autoTable : typeof atMod.default === "function" ? atMod.default : atMod.default?.default;
  const doc = new jsPDF({ unit: "pt", format: "letter" });
  const sample = days.some(({ d }) => d.sample);
  doc.setFontSize(15); doc.text(title, 40, 46);
  doc.setFontSize(9); doc.text(`${pack.name}. Generated by Cubby from the provider's notes; each entry keeps the note it came from.${sample ? " FICTIONAL DEMO DATA." : ""}`, 40, 62, { maxWidth: 530 });
  let y = 76;
  days.forEach(({ d, flags }, i) => {
    if (i > 0) { doc.addPage(); y = 46; }
    if (days.length > 1) { doc.setFontSize(12); doc.text(new Date(d.date + "T12:00:00").toDateString(), 40, y); y += 10; }
    const p = presence(d);
    autoTable(doc, { startY: y, head: [["Child", "In", "Dropped off by", "Out", "Picked up by"]], body: d.roster.filter((c) => p.kids[c.id].in != null || p.kids[c.id].out != null).map((c) => [c.full ?? c.name, fmt(p.kids[c.id].in), p.kids[c.id].inEv?.by ?? "", fmt(p.kids[c.id].out), p.kids[c.id].outEv?.by ?? ""]), styles: { fontSize: 8 } });
    autoTable(doc, { head: [["Time", "Who", "Entry", "From note"]], body: logRows(d).map((r) => [r.time, r.who, r.what, r.quote]), styles: { fontSize: 7, cellPadding: 3 }, columnStyles: { 3: { cellWidth: 200 } } });
    autoTable(doc, { head: [["Open flag", "Rule"]], body: flags.length ? flags.map((f) => [f.title, f.cite?.sec ?? ""]) : [["None", ""]], styles: { fontSize: 8 } });
  });
  doc.save(`${base}.pdf`);
}
